/**
 * Pure and tested product filtering function
 */
export function filterProducts(
  products: ProductCatalogItem[],
  filters: ProductFilters
): ProductCatalogItem[] {
  return products.filter((p) => {
    // 1. Subcategory filter
    if (filters.subCategories && filters.subCategories.length > 0) {
      if (!filters.subCategories.includes(p.subCategory)) {
        return false;
      }
    }

    // 2. Brand filter
    if (filters.brands && filters.brands.length > 0) {
      if (!filters.brands.includes(p.brand)) {
        return false;
      }
    }

    // 3. Min / Max Price
    if (filters.minPrice !== undefined && p.price < filters.minPrice) {
      return false;
    }
    if (filters.maxPrice !== undefined && p.price > filters.maxPrice) {
      return false;
    }

    // 4. Pharmaceutical form
    if (filters.forms && filters.forms.length > 0) {
      if (!filters.forms.includes(p.form)) {
        return false;
      }
    }

    // 5. Target Audience
    if (filters.targetAudiences && filters.targetAudiences.length > 0) {
      if (!filters.targetAudiences.includes(p.targetAudience)) {
        return false;
      }
    }

    // 6. Breastfeeding
    if (filters.breastfeeding && filters.breastfeeding.length > 0) {
      if (!filters.breastfeeding.includes(p.breastfeeding)) {
        return false;
      }
    }

    // 7. Pregnancy
    if (filters.pregnancy && filters.pregnancy.length > 0) {
      if (!filters.pregnancy.includes(p.pregnancy)) {
        return false;
      }
    }

    // 8. Pharmacy partner
    if (filters.pharmacies && filters.pharmacies.length > 0) {
      if (!filters.pharmacies.includes(p.partnerPharmacyId)) {
        return false;
      }
    }

    // 9. Available now
    if (filters.availableNow && !p.inStock) {
      return false;
    }

    // 10. Without prescription only
    if (filters.withoutPrescription && !p.withoutPrescription) {
      return false;
    }

    // 11. Search query
    if (filters.search && filters.search.trim()) {
      const q = filters.search.toLowerCase().trim();
      const matchName = p.name.toLowerCase().includes(q);
      const matchDesc = p.description.toLowerCase().includes(q);
      const matchBrand = p.brand.toLowerCase().includes(q);
      if (!matchName && !matchDesc && !matchBrand) {
        return false;
      }
    }

    return true;
  });
}

/**
 * Pure and tested product sorting function
 */
export function sortProducts(
  products: ProductCatalogItem[],
  sortBy: SortOption
): ProductCatalogItem[] {
  const cloned = [...products];

  switch (sortBy) {
    case 'price-asc':
      return cloned.sort((a, b) => a.price - b.price);
    case 'price-desc':
      return cloned.sort((a, b) => b.price - a.price);
    case 'newest':
      return cloned.sort((a, b) => {
        const da = a.createdAt ? new Date(a.createdAt).getTime() : 0;
        const db = b.createdAt ? new Date(b.createdAt).getTime() : 0;
        return db - da;
      });
    case 'rating':
      return cloned.sort((a, b) => (b.rating || 0) - (a.rating || 0));
    case 'relevance':
    default:
      // Sort by reviews and stock
      return cloned.sort((a, b) => (b.reviewCount || 0) - (a.reviewCount || 0));
  }
}
